/*
 * One distinct OUT record: a single write (count 0), a small multi-argument write whose arguments are in k_args
 * (kind 0), or a write-block table loaded from the user's data file (kind 2, offset is the table slot).
 */
#define RECORD_TABLE 2u
typedef struct startup_record {
    uint16_t command;
    uint16_t value;
    uint32_t count;
    uint32_t offset;
    uint8_t kind;
} startup_record;

typedef struct startup_table {
    uint16_t command;
    uint32_t count;
} startup_table;

struct ost_startup_data {
    unsigned char *tables[8];
};

